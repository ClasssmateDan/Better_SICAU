import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { Script } from 'node:vm';
import { createPreset } from '../dist/preset.mjs';
import { createReminderPlan } from '../dist/reminders.mjs';
import { buildQrTool } from './build-qr.mjs';

const root = new URL('../', import.meta.url);
const read = name => readFile(new URL(name, root), 'utf8');

export async function buildStatic() {
  const [model, preset, reminders, app, template, css, favicon, qrCore, transfer, guide, example] = await Promise.all([
    read('dist/model.mjs'), read('dist/preset.mjs'), read('dist/reminders.mjs'), read('dist/app.mjs'), read('dist/index.html'),
    read('dist/styles.css'), read('dist/favicon.svg'), read('qr-tool/dist/qr-core.js'),
    read('dist/transfer.mjs'), read('课表数据格式说明.md'), read('课表导入示例.json'),
  ]);
  // These local modules have no external dependencies. Keep their sources reusable,
  // and produce a classic script that also runs under file:// without module CORS.
  const modelBody = model.replace(/^export (?=(?:const|function) )/gm, '');
  const modelImport = /^import \{[\s\S]*?\} from '\.\/model\.mjs';\r?\n/;
  if (!modelImport.test(app)) throw new Error('app.mjs 的模型导入格式已改变，请更新构建脚本。');
  if (!modelImport.test(preset)) throw new Error('preset.mjs 的模型导入格式已改变，请更新构建脚本。');
  const presetImport = /^import \{ createPreset, fillKnownClassids \} from '\.\/preset\.mjs';\r?\n/m;
  if (!presetImport.test(app)) throw new Error('app.mjs 缺少截图课表导入。');
  const remindersImport = /^import \{ BrowserReminderController, createReminderPlan \} from '\.\/reminders\.mjs';\r?\n/m;
  const transferImport = /^import \{ parseTimetableFile, exportTimetableFile, summarizeTimetable \} from '\.\/transfer\.mjs';\r?\n/m;
  if (!remindersImport.test(app) || !modelImport.test(reminders)) throw new Error('提醒模块导入格式已改变，请更新构建脚本。');
  const qrDocument = await buildQrTool();
  const qrMarker = "const qrDocument = /* qr:document */ '';";
  if (!app.includes(qrMarker)) throw new Error('缺少二维码工具的内嵌入口。');
  if (!transferImport.test(app)) throw new Error('缺少课表导入导出模块。');
  const guideMarker = "const importGuide = /* transfer:guide */ '';";
  const exampleMarker = "const importExample = /* transfer:example */ '';";
  if (!app.includes(guideMarker) || !app.includes(exampleMarker)) throw new Error('缺少导入格式说明入口。');
  const appBody = app.replace(modelImport, '').replace(presetImport, '').replace(remindersImport, '').replace(transferImport, '')
    .replace(qrMarker, () => `const qrDocument = ${JSON.stringify(qrDocument)};`)
    .replace(guideMarker, () => `const importGuide = ${JSON.stringify(guide)};`)
    .replace(exampleMarker, () => `const importExample = ${JSON.stringify(example)};`);
  const presetBody = preset.replace(modelImport, '').replace(/^export (?=(?:const|function) )/gm, '');
  const reminderBody = reminders.replace(modelImport, '').replace(/^export (?=(?:const|function|class) )/gm, '');
  const transferBody = transfer.replace(modelImport, '').replace(/^export (?=(?:const|function) )/gm, '');
  const bundle = `// Generated by scripts/build.mjs; edit the .mjs sources instead.\n(() => {\n'use strict';\n${modelBody}\n${presetBody}\n${reminderBody}\n${transferBody}\n${qrCore}\n${appBody}\n})();\n`;
  new Script(bundle, { filename: 'app.js' });

  const replacements = [
    ['<link rel="icon" href="./favicon.svg" type="image/svg+xml">', `<link rel="icon" href="data:image/svg+xml,${encodeURIComponent(favicon.trim())}" type="image/svg+xml">`],
    ['<link rel="stylesheet" href="./styles.css">', `<style>\n${css}\n</style>`],
    ['<script defer src="./app.js"></script>', ''],
    ['</body>', `<script>\n${bundle.replace(/<\/script/gi, '<\\/script')}\n</script>\n</body>`],
  ];
  let standalone = template;
  for (const [before, after] of replacements) {
    if (!standalone.includes(before)) throw new Error(`页面缺少构建入口：${before}`);
    standalone = standalone.replace(before, () => after);
  }
  await writeFile(new URL('dist/app.js', root), bundle);
  await writeFile(new URL('index.html', root), standalone);
  await writeFile(new URL('空白课表.json', root), JSON.stringify(createPreset(), null, 2) + '\n');
  await writeFile(new URL('reminder-plan.json', root), JSON.stringify(createReminderPlan(createPreset()), null, 2) + '\n');
  return { bundle, standalone };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await buildStatic();
  console.log('静态网页已生成：index.html。双击即可打开，无需启动服务。');
}
